#!/usr/bin/env node
// Generate the block catalog the docs-generation skill reads, from the plugin that registers
// the blocks.
//
// The catalog used to be maintained by hand in four places: the skill's SKILL.md, a hardcoded
// allow-list in a downstream wrapper's verification reference, a prose count in its vendoring
// notes, and the plugin itself. They drifted — one copy documented 13 blocks while the plugin
// registered 17 — and the drift is invisible until an agent emits an attribute the renderer
// silently drops.
//
//   node scripts/generate-block-catalog.mjs           # write the catalog
//   node scripts/generate-block-catalog.mjs --check   # fail if it is out of date (for CI)

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const blocksRoot = path.join(root, "plugins", "docspress-blocks", "blocks");
const target = path.join(
  root,
  ".agents",
  "skills",
  "generate-docs-from-source",
  "references",
  "block-catalog.md"
);

// Blocks the reading interface owns. An author puts these in a Site Editor template, not in a
// Markdown page, so the catalog lists them separately rather than alongside the page blocks.
const TEMPLATE_BLOCKS = new Set(["version-switcher", "version-notice"]);

// Blocks the synchronization writes and nobody authors. Listing one would invite an agent to
// emit it, and a hand-written sentinel is worse than none: it claims a Page is managed when no
// run produced it. The Action is the only thing that writes these.
const INTERNAL_BLOCKS = new Set(["sentinel"]);

const HEADER = `<!-- Generated by scripts/generate-block-catalog.mjs from plugins/docspress-blocks/blocks/*/block.php.
     Do not edit by hand: run \`node scripts/generate-block-catalog.mjs\` instead. -->

# DocsPress block catalog

Every block the plugin registers, with the attributes and accepted values read out of its
\`block.php\`. When a target site runs a different plugin revision, **that revision's source is
the authority** — \`blocks/<name>/block.php\`, where each \`docspress_blocks_allowed_value()\`
call names the valid values for one attribute.

Accepted values are matched case-insensitively and punctuation is stripped, because
\`docspress_blocks_allowed_value()\` runs \`sanitize_key()\` on the incoming value first. The
lists below are spelled as the plugin stores them; an HTTP method written \`GET\` matches
\`get\` and renders uppercase. A value outside the list falls back to the block's default
**silently**, which is why generating this file beats remembering it.

## Writing a block into Markdown

Prefer ordinary Markdown. A fence with an info string already produces a Colorful Code block,
and a \`> [!WARNING]\` quote already produces a Callout, so most code and admonition content
needs no block config at all:

\`\`\`\`markdown
\`\`\`php title="includes/Core/Bootstrap.php" lines="88-104" {91}
public function run() {
    $this->initialize_modules();
}
\`\`\`
\`\`\`\`

Where a block has no Markdown spelling, use the **envelope**: an authoritative JSON config
followed by a human-readable projection of it. The config wins; the visible Markdown below it
is what a reviewer reads in a pull request and what GitHub renders.

\`\`\`markdown
<!-- docspress:block
{
  "version": 1,
  "name": "docspress/callout",
  "attrs": {
    "tone": "warning",
    "title": "Routes appear only when their module is enabled",
    "content": "<p>Requests to a disabled module's routes return <code>404 rest_no_route</code>.</p>"
  }
}
-->
> [!WARNING]
>
> **Routes appear only when their module is enabled**
>
> Requests to a disabled module's routes return \\\`404 rest_no_route\\\`.
<!-- /docspress:block -->
\`\`\`

Rules for the config: \`version\` is \`1\`; JSON must be valid and compact in its values; escape
quotes, backslashes, control characters, and literal newlines inside attribute strings; no
trailing commas, no JavaScript object syntax, no invented attributes, no custom colors. The
plugin inherits colour, typography, radius, borders, and light/dark presentation from the
active preset.

The older form — a bare \`<!-- wp:docspress/name {...} /-->\` comment — is still accepted input,
but it is legacy: it gives a reviewer a wall of JSON and no readable projection. Run
\`npm run migrate:markdown-blocks\` to convert a repository's existing pages.
`;

function unquote(value) {
  const text = String(value).trim();
  const match = text.match(/^'((?:[^'\\]|\\.)*)'$|^"((?:[^"\\]|\\.)*)"$/s);
  if (!match) {
    return text;
  }
  return (match[1] ?? match[2]).replace(/\\(['"\\])/g, "$1");
}

// The allow-list is usually a literal, but a block may pass `array_keys( some_map() )` when
// the same list also carries labels. Resolve that by reading the map the function returns,
// so the enum column stays populated instead of silently going blank.
function resolveAllowedList(allowed, source) {
  const indirect = allowed.match(/^array_keys\(\s*(\w+)\(\s*\)\s*\)$/);
  if (!indirect) {
    return allowed;
  }

  const start = source.indexOf(`function ${indirect[1]}(`);
  if (start === -1) {
    return "";
  }

  const body = source.slice(start, source.indexOf("\n}", start));
  // Keys only: 'hook' => __( 'action', … ) contributes `hook`, not `action`.
  return (body.match(/'((?:[^'\\]|\\.)*)'\s*=>/g) || []).join(",");
}

// `array( 'a', 'b', 'c' )` → ["a", "b", "c"]
function parseStringArray(body) {
  const values = [];
  const pattern = /'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"/g;
  let match;
  while ((match = pattern.exec(body))) {
    values.push((match[1] ?? match[2]).replace(/\\(['"\\])/g, "$1"));
  }
  return values;
}

// Every docspress_blocks_allowed_value( $x, array( … ), 'fallback' ) in the file, keyed by the
// attribute the first argument reads. This is what makes the enum columns real rather than
// remembered.
function collectAllowedValues(source) {
  const enums = new Map();
  const pattern = /docspress_blocks_allowed_value\(\s*([\s\S]*?)\s*,\s*(array\([\s\S]*?\)|array_keys\(\s*\w+\(\s*\)\s*\))\s*,\s*('[^']*'|"[^"]*")\s*\)/g;
  let match;
  while ((match = pattern.exec(source))) {
    const [, subject, allowed, fallback] = match;
    const arrayBody = resolveAllowedList(allowed, source);
    const attribute = subject.match(/\[\s*'([a-zA-Z]+)'\s*\]/)?.[1]
      ?? subject.match(/\$([a-z_]+)/)?.[1];
    if (!attribute) {
      continue;
    }
    enums.set(attribute, {
      values: parseStringArray(arrayBody),
      fallback: unquote(fallback)
    });
  }
  return enums;
}

function collectAttributes(source) {
  const start = source.indexOf("'attributes'");
  if (start === -1) {
    return [];
  }

  const attributes = [];
  const pattern = /'([a-zA-Z]+)'\s*=>\s*array\(\s*'type'\s*=>\s*'([a-z]+)'\s*(?:,\s*'default'\s*=>\s*([\s\S]*?))?\s*\),?\s*$/gm;
  const region = source.slice(start);
  let match;
  while ((match = pattern.exec(region))) {
    const [, name, type, rawDefault] = match;
    attributes.push({
      name,
      type,
      default: rawDefault === undefined ? "" : summarizeDefault(rawDefault)
    });
  }
  return attributes;
}

function summarizeDefault(raw) {
  const text = String(raw).trim().replace(/,$/, "");
  if (text === "array()" || text.startsWith("$") || text.includes("(")) {
    // A computed or structural default is not useful in a table; the block's own guide shows it.
    return "";
  }
  if (text === "true" || text === "false" || /^-?\d+$/.test(text)) {
    return `\`${text}\``;
  }
  const value = unquote(text);
  // A multi-line default is a body, not a table cell — including one written as an escape
  // sequence in a PHP double-quoted string, which unquoting leaves intact.
  if (value === "" || /\n|\\n/.test(value) || value.length > 48) {
    return "";
  }
  return `\`${value}\``;
}

function renderBlock(name, attributes, enums) {
  const rows = attributes.map((attribute) => {
    const enumeration = enums.get(attribute.name);
    const accepted = enumeration
      ? enumeration.values.map((value) => `\`${value}\``).join(", ")
      : "";
    return `| \`${attribute.name}\` | ${attribute.type} | ${attribute.default} | ${accepted} |`;
  });

  return [
    `### \`docspress/${name}\``,
    "",
    "| Attribute | Type | Default | Accepted values |",
    "| --- | --- | --- | --- |",
    ...rows,
    ""
  ].join("\n");
}

async function build() {
  const entries = (await fs.readdir(blocksRoot, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  const pageBlocks = [];
  const templateBlocks = [];

  for (const name of entries) {
    if (INTERNAL_BLOCKS.has(name)) {
      continue;
    }

    const source = await fs.readFile(path.join(blocksRoot, name, "block.php"), "utf8");
    const rendered = renderBlock(name, collectAttributes(source), collectAllowedValues(source));
    (TEMPLATE_BLOCKS.has(name) ? templateBlocks : pageBlocks).push(rendered);
  }

  return [
    HEADER,
    `## Page blocks (${pageBlocks.length})`,
    "",
    "Blocks an author places in a Markdown page.",
    "",
    ...pageBlocks,
    `## Template blocks (${templateBlocks.length})`,
    "",
    "The reading interface owns these. Place them in a Site Editor template, not in page",
    "Markdown — the Header carries the version switcher and the Page template carries the",
    "notice, so every versioned page gets one and unversioned pages get none.",
    "",
    ...templateBlocks
  ].join("\n");
}

const catalog = await build();

if (process.argv.includes("--check")) {
  const existing = await fs.readFile(target, "utf8").catch(() => "");
  if (existing !== catalog) {
    console.error(
      "Block catalog is out of date. Run: node scripts/generate-block-catalog.mjs"
    );
    process.exit(1);
  }
  console.log("Block catalog is current.");
} else {
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, catalog);
  console.log(`Wrote ${path.relative(root, target)}`);
}
